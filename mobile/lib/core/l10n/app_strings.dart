/// App languages: English plus the ten most widely spoken Indian languages.
/// Native names are shown in the language picker so a user can find their own language without reading English.
class AppLanguage {
  final String code;
  final String nativeName;
  final String englishName;

  const AppLanguage(this.code, this.nativeName, this.englishName);

  static const List<AppLanguage> all = [
    AppLanguage('en', 'English', 'English'),
    AppLanguage('hi', 'हिन्दी', 'Hindi'),
    AppLanguage('bn', 'বাংলা', 'Bengali'),
    AppLanguage('mr', 'मराठी', 'Marathi'),
    AppLanguage('te', 'తెలుగు', 'Telugu'),
    AppLanguage('ta', 'தமிழ்', 'Tamil'),
    AppLanguage('gu', 'ગુજરાતી', 'Gujarati'),
    AppLanguage('ur', 'اردو', 'Urdu'),
    AppLanguage('kn', 'ಕನ್ನಡ', 'Kannada'),
    AppLanguage('or', 'ଓଡ଼ିଆ', 'Odia'),
    AppLanguage('ml', 'മലയാളം', 'Malayalam'),
  ];

  static List<Locale> get locales => all.map((l) => Locale(l.code)).toList();

  static bool isSupported(String code) => all.any((l) => l.code == code);
}

/// Current app language. Persisted in Hive; unsupported saved values (older builds offered es/fr) fall back to English.
class LocaleNotifier extends StateNotifier<Locale> {
  LocaleNotifier() : super(Locale(_initialCode()));

  static String _initialCode() {
    final saved = LocalCache.getLanguage();
    return AppLanguage.isSupported(saved) ? saved : 'en';
  }

  Future<void> setLanguage(String code) async {
    if (!AppLanguage.isSupported(code)) return;
    state = Locale(code);
    await LocalCache.setLanguage(code);
  }
}

final localeProvider = StateNotifierProvider<LocaleNotifier, Locale>((ref) => LocaleNotifier());

